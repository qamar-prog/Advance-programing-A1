CREATE TABLE courses (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    course_code character varying(20) NOT NULL,
    name character varying(200) NOT NULL,
    credit_hours integer NOT NULL,
    CONSTRAINT pk_courses PRIMARY KEY (id),
    CONSTRAINT ck_courses_credit_hours CHECK (credit_hours BETWEEN 1 AND 4)
);

CREATE TABLE students (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    student_number character varying(20) NOT NULL,
    first_name character varying(100) NOT NULL,
    last_name character varying(100) NOT NULL,
    CONSTRAINT pk_students PRIMARY KEY (id)
);

CREATE TABLE enrollments (
    student_id integer NOT NULL,
    course_id integer NOT NULL,
    mark integer,
    CONSTRAINT pk_enrollments PRIMARY KEY (student_id, course_id),
    CONSTRAINT ck_enrollments_mark CHECK (mark IS NULL OR mark BETWEEN 0 AND 100),
    CONSTRAINT fk_enrollments_courses_course_id FOREIGN KEY (course_id) REFERENCES courses (id) ON DELETE CASCADE,
    CONSTRAINT fk_enrollments_students_student_id FOREIGN KEY (student_id) REFERENCES students (id) ON DELETE CASCADE
);

CREATE TABLE users (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    username character varying(100) NOT NULL,
    password_hash character varying(500) NOT NULL,
    role character varying(30) NOT NULL,
    student_id integer,
    CONSTRAINT pk_users PRIMARY KEY (id),
    CONSTRAINT ck_users_role CHECK (role IN ('Teacher', 'Student')),
    CONSTRAINT fk_users_students_student_id FOREIGN KEY (student_id) REFERENCES students (id) ON DELETE SET NULL
);

